def load_sequence(fasta, text):
    """Sequence from --text (any string) or from a FASTA file."""
    if text is not None:
        return text
    if not fasta:
        raise ValueError("give --fasta FILE or --text STRING")
    if not os.path.isfile(fasta):
        raise FileNotFoundError(f"file not found: {fasta}")
    return read_fasta(fasta)


