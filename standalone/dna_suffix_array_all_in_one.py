def reference(text: str, pattern: str) -> List[int]:
    """Trusted brute-force answer (overlapping matches allowed)."""
    out, start = [], text.find(pattern)
    while start != -1:
        out.append(start)
        start = text.find(pattern, start + 1)
    return out


def _structures():
    return [cls() for cls in ALL_MATCHERS] + [SuffixTrie(), KmerIndex(3)]


def check_search_case(text: str, pattern: str) -> List[str]:
    """Return a list of problems (empty list = all structures correct)."""
    problems = []
    expected = reference(text, pattern)
    for m in _structures():
        if isinstance(m, SuffixTrie) and len(text) > 600:
            continue  # the trie needs O(n^2) memory by design - skip the long cases
        try:
            m.preprocess(text)
            got = m.find_all(pattern)
            if got != expected:
                problems.append(f"{m.name}: expected {expected[:5]}, got {got[:5]}")
            if m.count(pattern) != len(expected):
                problems.append(f"{m.name}: count mismatch")
        except Exception as exc:  # any crash is a failure
            problems.append(f"{m.name}: raised {type(exc).__name__}: {exc}")
    return problems


def check_invariants(text: str) -> List[str]:
    """Suffix array sorted + permutation, LCP vs brute force, BWT round trip."""
    problems = []
    try:
        sa = SuffixArray(text)
        t = sa.text
        if sorted(sa.sa) != list(range(len(t))):
            problems.append("SA is not a permutation")
        suffixes = [t[i:] for i in sa.sa]
        if suffixes != sorted(suffixes):
            problems.append("suffixes not sorted")
        if len(text) <= 800:
            lcp = LCPArray(text, sa.sa)
            for i in range(1, len(sa)):
                a, b = suffixes[i - 1], suffixes[i]
                k = 0
                while k < min(len(a), len(b)) and a[k] == b[k]:
                    k += 1
                if lcp.get(i) != k:
                    problems.append(f"LCP wrong at row {i}")
                    break
        if BWT(text, sa.sa).inverse() != terminate(text):
            problems.append("BWT inverse != original")
    except Exception as exc:
        problems.append(f"invariants raised {type(exc).__name__}: {exc}")
    return problems


def check_empty_pattern_rejected() -> List[str]:
    """Every structure must reject the empty pattern with ValueError (no crash, no wrong answer)."""
    problems = []
    for m in _structures():
        m.preprocess("ACGT")
        try:
            m.find_all("")
            problems.append(f"{m.name}: accepted an empty pattern")
        except ValueError:
            pass
        except Exception as exc:
            problems.append(f"{m.name}: wrong exception {type(exc).__name__}")
    return problems


def check_applications() -> List[str]:
    """Repeats, genome comparison and approximate search on degenerate inputs."""
    problems = []
    try:
        if longest_repeated_substring("")[1] != 0:
            problems.append("LRS of empty text should be 0")
        if longest_repeated_substring("A")[1] != 0:
            problems.append("LRS of one char should be 0")
        if longest_repeated_substring("AAAA")[1] != 3:
            problems.append("LRS of AAAA should be 3")
        if longest_common_substring("", "ACGT")[1] != 0:
            problems.append("LCS with empty text should be 0")
        if longest_common_substring("AC#GT", "GT#AC")[1] != 2:  # 'AC', 'GT' (and '#') are shared
            problems.append("LCS with '#' in the input is wrong")
        mm = _structures()[2]
        mm.preprocess("ACGTACGT")
        if approximate_search("ACGTACGT", "ACGTACGTAA", 2, mm) != []:
            problems.append("approximate: pattern longer than text should give []")
        if [p for p, _ in approximate_search("ACGTACGT", "ACGA", 1, mm)] != [0, 4]:
            problems.append("approximate: expected hits at 0 and 4")
        if [p for p, _ in approximate_search("ACGTACGT", "TT", 5, mm)] != list(range(7)):
            problems.append("approximate: k >= m should match everywhere")
    except Exception as exc:
        problems.append(f"applications raised {type(exc).__name__}: {exc}")
    return problems


def run_edge_cases(verbose: bool = True) -> Dict[str, List[str]]:
    """Run everything; returns {case name: problems} for failing cases only."""
    failures: Dict[str, List[str]] = {}
    if verbose:
        print(f"{'#':>2}  {'edge case':<44} result")
    for i, (name, text, pattern) in enumerate(EDGE_CASES, 1):
        problems = check_search_case(text, pattern) + check_invariants(text)
        if problems:
            failures[name] = problems
        if verbose:
            shown = len(reference(text, pattern))
            print(f"{i:>2}  {name:<44} {'FAIL' if problems else 'PASS'}   ({shown} match(es))")
            for p in problems:
                print("      -", p)
    for name, fn in [("empty pattern rejected cleanly", check_empty_pattern_rejected),
                     ("applications on degenerate input", check_applications)]:
        problems = fn()
        if problems:
            failures[name] = problems
        if verbose:
            print(f"{'':>2}  {name:<44} {'FAIL' if problems else 'PASS'}")
            for p in problems:
                print("      -", p)
    if verbose:
        total = len(EDGE_CASES) + 2
        print(f"\n{total - len(failures)}/{total} edge-case groups passed "
              f"(6 search structures compared against a brute-force reference).")
    return failures


