# ---------------------------------------------------------------------------
# Suffix trie (linked structure)
# ---------------------------------------------------------------------------
class _TrieNode:
    __slots__ = ("children", "pos")

    def __init__(self):
        self.children: Dict[str, "_TrieNode"] = {}
        self.pos: int = -1  # start position of the suffix that ends here (leaf), else -1


class SuffixTrie(PatternMatcherADT):
    """
    Uncompressed suffix trie built from linked nodes.
    Build  : O(n^2) time and O(n^2) nodes  (n suffixes, each up to n characters)
    Search : O(m) to reach the node, + O(size of subtree) to list the positions
    """
    name = "Suffix Trie"

    def preprocess(self, text: str) -> None:
        self.text = text
        self.root = _TrieNode()
        self.node_count = 1
        t = terminate(text)
        for i in range(len(t)):
            node = self.root
            for ch in t[i:]:
                nxt = node.children.get(ch)
                if nxt is None:
                    nxt = _TrieNode()
                    node.children[ch] = nxt
                    self.node_count += 1
                node = nxt
            node.pos = i
        self.sentinel = t[-1]

    def find_all(self, pattern: str) -> List[int]:
        check_pattern(pattern)
        if self.sentinel in pattern:
            return []
        node = self.root
        for ch in pattern:
            node = node.children.get(ch)
            if node is None:
                return []
        out, stack = [], [node]
        while stack:  # collect every leaf below the node
            cur = stack.pop()
            if cur.pos >= 0:
                out.append(cur.pos)
            stack.extend(cur.children.values())
        return sorted(out)


