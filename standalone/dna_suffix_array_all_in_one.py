def trie_vs_array(sizes=(100, 200, 400, 800), seed: int = 5, verbose: bool = True):
    """Build a suffix trie and a suffix array on the same DNA; report size and time."""

    rows = []
    if verbose:
        print(f"{'n':>6} | {'trie nodes':>11} {'n^2/2':>9} {'trie MB':>8} {'trie s':>8} "
              f"| {'SA entries':>10} {'SA MB':>7} {'SA s':>8} | memory ratio")
    for n in sizes:
        g = random_genome(n, seed=seed)

        tracemalloc.start()
        t0 = time.perf_counter()
        trie = SuffixTrie()
        trie.preprocess(g)
        t_trie = time.perf_counter() - t0
        trie_mb = tracemalloc.get_traced_memory()[1] / 1e6
        tracemalloc.stop()

        tracemalloc.start()
        t0 = time.perf_counter()
        sa = SuffixArray(g)
        t_sa = time.perf_counter() - t0
        sa_mb = tracemalloc.get_traced_memory()[1] / 1e6
        tracemalloc.stop()

        row = {"n": n, "trie_nodes": trie.node_count, "half_n_squared": n * n // 2,
               "trie_mb": round(trie_mb, 2), "trie_s": round(t_trie, 4),
               "sa_entries": len(sa), "sa_mb": round(sa_mb, 3), "sa_s": round(t_sa, 4),
               "memory_ratio": round(trie_mb / max(sa_mb, 1e-9), 1)}
        rows.append(row)
        if verbose:
            print(f"{n:>6} | {row['trie_nodes']:>11,} {row['half_n_squared']:>9,} {row['trie_mb']:>8.2f} "
                  f"{row['trie_s']:>8.3f} | {row['sa_entries']:>10,} {row['sa_mb']:>7.3f} "
                  f"{row['sa_s']:>8.4f} | {row['memory_ratio']}x")
    if verbose:
        print("Trie nodes grow like n^2/2; the suffix array stores exactly n+1 integers.")
    return rows


