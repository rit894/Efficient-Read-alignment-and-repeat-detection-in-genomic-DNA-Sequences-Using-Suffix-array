# k-mer hash index
# ---------------------------------------------------------------------------
class KmerIndex(PatternMatcherADT):
    """
    Hash index of every k-mer. A pattern of length >= k is looked up by its
    first k characters and the candidates are verified.
    Build  : O(n) time, O(n) space
    Search : O(1 + candidates * m) for m >= k.  For m < k the index is useless
             and we fall back to a scan (flagged in `fallback_used`).
    """
    name = "k-mer Index"

    def __init__(self, k: int = 8):
        if k < 1:
            raise ValueError("k must be >= 1")
        self.k = k
        self.fallback_used = False

    def preprocess(self, text: str) -> None:
        self.text = text
        self.table: Dict[str, List[int]] = {}
        for i in range(len(text) - self.k + 1):
            self.table.setdefault(text[i:i + self.k], []).append(i)

    def find_all(self, pattern: str) -> List[int]:
        check_pattern(pattern)
        m, t = len(pattern), self.text
        if m < self.k:  # cannot use the index: scan instead
            self.fallback_used = True
            return [i for i in range(len(t) - m + 1) if t[i:i + m] == pattern]
        return [p for p in self.table.get(pattern[:self.k], []) if t[p:p + m] == pattern]


ALTERNATIVE_MATCHERS = [SuffixTrie, KmerIndex]


